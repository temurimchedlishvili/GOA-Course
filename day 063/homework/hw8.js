// მომხმარებელს ვეკითხებით საწყის რიცხვს
let number = Number(prompt("შეიყვანეთ რიცხვი:"));

// თუ მომხმარებელი სწორად შეიყვანს რიცხვს
if (!isNaN(number)) {
while (number >= 0) {
    console.log(number);   // დაბეჭდავს მიმდინარე რიცხვს
    // alert(number);      // თუ გინდა თითო ნაბიჯი ფანჯარაში გამოჩნდეს
    number--;              // ერთი ნაბიჯით დაკლება
}
} else {
alert("გთხოვთ შეიყვანეთ სწორი რიცხვი!");
}
