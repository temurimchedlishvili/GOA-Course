// ცვლადები
let i = 1;        // საწყისი რიცხვი
let sum = 0;      // ჯამის შესანახი ცვლადი

// while ციკლი
while (i <= 100) {
  sum = sum + i;  // ჯამში დავამატოთ i
  i++;            // გავზარდოთ i
}

// შედეგის გამოტანა
console.log("1-დან 100-მდე რიცხვების ჯამი არის: " + sum);
alert("1-დან 100-მდე რიცხვების ჯამი არის: " + sum);
