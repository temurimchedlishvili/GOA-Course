// for loop გამოიყენება, როცა გვსურს ერთი და იგივე მოქმედება რამდენჯერმე გავიმეოროთ.

// for loop-ის სტრუქტურაა:
// for (საწყისი_მნიშვნელობა; პირობა; ნაბიჯი) {
//     შესასრულებელი კოდი
// }

// მაგალითი:
for (let i = 1; i <= 5; i++) {
// ეს ნაწილი შესრულდება იმდენჯერ, რამდენჯერაც პირობა (i <= 5) ჭეშმარიტია.

console.log("რიცხვი არის:", i); // ბეჭდავს 1-დან 5-მდე რიცხვებს
}

// ახსნა ნაბიჯ-ნაბიჯ:
// 1️ let i = 1  → ცვლადი i იწყება მნიშვნელობით 1
// 2️ i <= 5     → ლუპი გაგრძელდება სანამ i ნაკლებია ან ტოლია 5-ის
// 3️ console.log() → თითოეულ წრეზე გამოიტანს i-ს მნიშვნელობას
// 4️ i++         → ყოველ ჯერზე i ერთი ერთეულით იზრდება
// როცა i გახდება 6 → პირობა (i <= 5) იქნება ცრუ, და ციკლი შეწყდება