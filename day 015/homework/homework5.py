my_list = [1, 2, 3]

# append() - ამატებს ელემენტს სიის ბოლოს
my_list.append(4)  # [1, 2, 3, 4]

# pop() - შლის სიის ბოლო ელემენტს (ან მითითებულ ინდექსზე არსებულს) და აბრუნებს მას
last_item = my_list.pop()  # last_item = 4, my_list = [1, 2, 3]

# insert() - ამატებს ელემენტს მითითებულ ინდექსზე, ხოლო დანარჩენ ელემენტებს ერთი ნაბიჯით აჩოჩებს
my_list.insert(1, 77)  # [1, 77, 2, 3]
