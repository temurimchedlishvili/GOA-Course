# ვქმნით სიას მოცემული მნიშვნელობებით
numbers = [1, 4, 3, 6, 9, 11, 17, 13, 26, 30]

# ვპოულობთ ლუწი რიცხვების ჯამს
even_sum = sum(num for num in numbers if num % 2 == 0)
# even_sum არის ცვლადი, რომელიც ინახავს ლუწი რიცხვების ჯამს მოცემული სიიდან.

# ვპოულობთ კენტი რიცხვების რაოდენობას
odd_count = sum(1 for num in numbers if num % 2 != 0)
#odd_count არის ცვლადი, რომელიც ინახავს კენტი რიცხვების რაოდენობას მოცემული სიიდან.