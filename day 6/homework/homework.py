# მომხმარებელს შემოაქვს რიცხვი
num = int(input("shemoiyvanet ricxvi: "))

# კენტი რიცხვების ჯამის ინიციალიზაცია
odd_sum = 0

# for ციკლი 1-დან შეყვანილ რიცხვამდე
for i in range(1, num + 1):
    if i % 2 != 0:  # თუ რიცხვი კენტია
        odd_sum += i

# შედეგის გამოტანა
print("კენტი რიცხვების ჯამი:", odd_sum)