// მომხმარებლისგან რიცხვის მიღება
let input = prompt("შეიყვანეთ რიცხვი:");

// prompt ყოველთვის აბრუნებს სტრინგს, ამიტომ გადავიყვანოთ რიცხვში
let number = Number(input);

// ჯამი და სხვაობა 10-სთან (მაგალითად)
console.log("რიცხვის დამატება 10-სთან: " + (number + 10));
console.log("რიცხვის შეცილება 10-დან: " + (number - 10));

// ნამრავლი და განაყოფი 10-ით
console.log("რიცხვის გამრავლება 10-ზე: " + (number * 10));
console.log("რიცხვის გაყოფა 10-ზე: " + (number / 10));
