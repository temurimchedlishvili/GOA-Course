// JavaScript-ში ცვლადების შესაქმნელად ვიყენებთ საკვანძო სიტყვებს: var, let და const

// var – ძველი მეთოდია, დღეს ნაკლებად გამოიყენება
var oldVariable = "ეს var-ით შექმნილი ცვლადია";

// let – გამოიყენება ცვლადებისთვის, რომელთა მნიშვნელობა შეიძლება შეიცვალოს
let age = 20;

// const – გამოიყენება ცვლადებისთვის, რომელთა მნიშვნელობა უცვლელია
const pi = 3.14;

// ცვლადების ტიპები JavaScript-ში

// 1) String (ტექსტური მნიშვნელობა)
let name = "Temuri";

// 2) Number (რიცხვები: მთელი ან ათწილადი)
let number = 25;
let price = 19.99;

// 3) Boolean (ლოგიკური მნიშვნელობა: true ან false)
let isOnline = true;
let isAdmin = false;

// 5) Null (განსაკუთრებულად ცარიელი მნიშვნელობა)
let emptyValue = null;

// 7) Array (მასივი – ელემენტების სია)
let colors = ["red", "green", "blue"];
