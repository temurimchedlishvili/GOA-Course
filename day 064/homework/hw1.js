// ფუნქციების შექმნა JavaScript-ში რამდენიმე ხერხით შეგვიძლია:

// 1) Function Declaration (ფუნქციის დეკლარაცია)
// → ეს არის კლასიკური გზა ფუნქციის შესაქმნელად.
// → ფუნქცია მთლიანად "hoisting"-დება (ანუ კოდის შესრულებამდე იხსნება მეხსიერებაში).
function add(a, b) {
return a + b;
}

// 2) Function Expression (ფუნქციის გამოხატულება)
// → ფუნქცია შეინახება ცვლადში როგორც მნიშვნელობა.
// → "hoisting"-ის დროს მხოლოდ ცვლადი იქმნება, ფუნქცია კი არა.
// → გამოიყენება მაშინ, როცა გვინდა მოქნილი კონტროლი.
const multiply = function(a, b) {
  return a * b;
};

// 3) Arrow Function (ისრისებური ფუნქცია)
// → მოკლე სინტაქსი ES6-დან.
// → არ აქვს საკუთარი "this", არამედ მშობლის "this"-ს იყენებს.
// → ხშირად გამოიყენება callback-ებში და მოკლე ფუნქციებში.
const divide = (a, b) => a / b;

// 4) Constructor Function (კონსტრუქტორი ფუნქცია)
// → გამოიყენება ობიექტების შესაქმნელად.
// → new საკვანძო სიტყვით იძახება.
// → ჩვეულებრივ ფუნქციას დიდ ასოობით ვიწყებთ.
function Person(name, age) {
this.name = name;
this.age = age;
}
const user = new Person("Temuri", 20);

// 5) Immediately Invoked Function Expression (IIFE)
// → ფუნქცია, რომელიც გამოძახებისთანავე სრულდება.
// → ძირითადად გამოიყენება კოდის იზოლაციისთვის (scope-ს შესაქმნელად).
(function() {
console.log("მე პირდაპირ შესრულებული ფუნქცია ვარ!");
})();
