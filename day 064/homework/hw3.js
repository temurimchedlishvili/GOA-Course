const fullName = function(firstName, lastName) {
  return firstName + " " + lastName;
};

// გამოსცადოთ
console.log(fullName("Temuri", "Mchedlishvili")); // → "Temuri Mchedlishvili"
console.log(fullName("Temuri", "Mchedlishvili")); // → "Temuri Mchedlishvili"
