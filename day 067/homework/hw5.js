// ვქმნით ობიექტს სახელით car
const car = {
  brand: "Toyota",   // მარკა
  model: "Corolla",  // მოდელი
  year: 2020         // გამოშვების წელი
};

// ვბეჭდავთ ყველა key-ს (საკვანძო სიტყვას)
console.log("Keys:", Object.keys(car));

// ვბეჭდავთ ყველა value-ს (მნიშვნელობას)
console.log("Values:", Object.values(car));
