let num; // ცვლადი მომხმარებლის შეყვანისთვის

do {
  // ვთხოვთ მომხმარებელს რიცხვის შეყვანას
num = parseFloat(prompt("შეიყვანე რიცხვი (უარყოფითი რომ შეჩერდეს):"));

// ვბეჭდავთ შეყვანილ რიცხვს, თუ ის დადებითია ან ნულის ტოლია
if (num >= 0) {
    console.log("შეიყვანე:", num);
}

} while (num >= 0); // ვაგრძელებთ მანამ, სანამ რიცხვი უარყოფითი არაა

console.log("შეყვანა დასრულდა, რადგან შეყვანილია უარყოფითი რიცხვი.");
