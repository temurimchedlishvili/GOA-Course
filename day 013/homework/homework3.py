# მომხმარებლის მიერ შემოყვანილი მთელი რიცხვი
number = int(input("შეიყვანეთ მთელი რიცხვი: "))

# რიცხვის გაზრდა ხუთით, თუ ის ლუწია

if number % 2 == 0:  # თუ რიცხვი ლუწია
    number += 5      # რიცხვი გავზარდოთ ხუთით

# შედეგის დაბეჭდვა
print(number)

